def test_insert_expansion_emits_primitives():
    """A BLOCK + INSERT in modelspace expands into world-coord LINE primitives."""
    dxf = (
        "0\nSECTION\n2\nHEADER\n9\n$INSUNITS\n70\n4\n0\nENDSEC\n"
        "0\nSECTION\n2\nBLOCKS\n"
        "0\nBLOCK\n8\n0\n2\nMYBLOCK\n10\n0.0\n20\n0.0\n30\n0.0\n"
        "0\nLINE\n8\n0\n10\n0.0\n20\n0.0\n11\n100.0\n21\n100.0\n"
        "0\nENDBLK\n0\nENDSEC\n"
        "0\nSECTION\n2\nENTITIES\n"
        "0\nINSERT\n8\n0\n2\nMYBLOCK\n10\n500.0\n20\n500.0\n41\n1.0\n42\n1.0\n50\n0.0\n"
        "0\nENDSEC\n0\nEOF\n"
    )
    parsed = _parse_dxf(dxf.encode("utf-8"), "synthetic.dxf")
    assert parsed.ok
    # The expanded LINE should be the only entity, and it should be at
    # world coords (500, 500) → (600, 600) (insert pt + block primitive).
    line_ents = [e for e in parsed.entities if e.get("type") == "LINE"]
    assert len(line_ents) == 1
    sp = line_ents[0]["startPoint"]
    ep = line_ents[0]["endPoint"]
    assert 499.0 <= sp["x"] <= 501.0 and 499.0 <= sp["y"] <= 501.0
    assert 599.0 <= ep["x"] <= 601.0 and 599.0 <= ep["y"] <= 601.0
    # The expanded primitive should be tagged with its source block name so
    # the classifier can apply block-name rules.
    assert line_ents[0].get("blockName") == "MYBLOCK"


def test_insert_expansion_with_rotation():
    """A rotated INSERT applies the rotation to its primitives."""
    dxf = (
        "0\nSECTION\n2\nHEADER\n9\n$INSUNITS\n70\n4\n0\nENDSEC\n"
        "0\nSECTION\n2\nBLOCKS\n"
        "0\nBLOCK\n8\n0\n2\nRB\n10\n0.0\n20\n0.0\n30\n0.0\n"
        "0\nLINE\n8\n0\n10\n100.0\n20\n0.0\n11\n200.0\n21\n0.0\n"
        "0\nENDBLK\n0\nENDSEC\n"
        "0\nSECTION\n2\nENTITIES\n"
        "0\nINSERT\n8\n0\n2\nRB\n10\n0.0\n20\n0.0\n41\n1.0\n42\n1.0\n50\n90.0\n"
        "0\nENDSEC\n0\nEOF\n"
    )
    parsed = _parse_dxf(dxf.encode("utf-8"), "rotated.dxf")
    line_ents = [e for e in parsed.entities if e.get("type") == "LINE"]
    assert len(line_ents) == 1
    sp = line_ents[0]["startPoint"]
    ep = line_ents[0]["endPoint"]
    # 90° rotation around base (0, 0) turns (100, 0) → (0, 100) and
    # (200, 0) → (0, 200).
    assert abs(sp["x"]) < 1.0 and abs(sp["y"] - 100.0) < 1.0
    assert abs(ep["x"]) < 1.0 and abs(ep["y"] - 200.0) < 1.0


def test_insert_with_unknown_block_passes_through():
    """An INSERT referencing an undefined block is kept as-is."""
    dxf = (
        "0\nSECTION\n2\nHEADER\n9\n$INSUNITS\n70\n4\n0\nENDSEC\n"
        "0\nSECTION\n2\nBLOCKS\n0\nENDSEC\n"
        "0\nSECTION\n2\nENTITIES\n"
        "0\nINSERT\n8\n0\n2\nMISSING\n10\n0.0\n20\n0.0\n41\n1.0\n42\n1.0\n50\n0.0\n"
        "0\nENDSEC\n0\nEOF\n"
    )
    parsed = _parse_dxf(dxf.encode("utf-8"), "missing.dxf")
    # INSERT remains in the entity list with blockName set.
    inserts = [e for e in parsed.entities if e.get("type") == "INSERT"]
    assert len(inserts) == 1
    assert inserts[0].get("blockName") == "MISSING"


