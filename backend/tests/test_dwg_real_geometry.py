def test_dxf_fixture_mech_parses_with_layers():
    p = FIXTURE_DIR / "tp104_mech.dxf"
    if not p.exists():
        pytest.skip("tp104_mech.dxf fixture missing — run scripts/regen_fixtures.sh")
    parsed = parse.parse_file(p, p.name)
    assert parsed.ok
    assert parsed.entity_count == 622
    assert len(parsed.layers) == 31
    # MECH has the typo layers PANTHOM / HIDDDEN plus MAIN OBJECT.
    layer_names = {l["name"] for l in parsed.layers}
    assert any("PHANTOM" in n.upper() or "PANTHOM" in n.upper() for n in layer_names)
    assert any("MAIN OBJECT" in n.upper() for n in layer_names)
    # Should classify into many distinct kinds (text/line/equipment/phantom/...).
    kinds = Counter(classify_dxf_entity(e) for e in parsed.entities)
    assert kinds.get("text", 0) > 50  # lots of real text labels
    assert kinds.get("equipment", 0) > 0  # MAIN OBJECT → equipment
    assert kinds.get("phantom", 0) > 0  # PANTHOM layer → phantom


def test_dxf_fixture_str_parses_with_entities():
    p = FIXTURE_DIR / "tp104_str.dxf"
    if not p.exists():
        pytest.skip("tp104_str.dxf fixture missing — run scripts/regen_fixtures.sh")
    parsed = parse.parse_file(p, p.name)
    assert parsed.ok
    # Real STR file should have thousands of geometric primitives after
    # INSERT expansion. If entity_count is ~2,275, the BLOCKS section
    # wasn't preserved or INSERT expansion didn't run.
    assert parsed.entity_count == 17_326
    assert len(parsed.layers) == 7
    # Should classify into beam / brace / gridline via block-name rules.
    kinds = Counter(classify_dxf_entity(e) for e in parsed.entities)
    assert kinds.get("beam", 0) > 0
    assert kinds.get("brace", 0) > 0
    assert kinds.get("gridline", 0) > 0
    # No DICTIONARY/FIELD/XRECORD pollution (these are OBJECTS not ENTITIES).
    type_counts = Counter(e["type"] for e in parsed.entities)
    assert "DICTIONARY" not in type_counts
    assert "FIELD" not in type_counts
    assert "XRECORD" not in type_counts
